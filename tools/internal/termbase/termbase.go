// Package termbase reads the FPSOT term base and turns it into AsciiDoc.
//
// Pages refer to terms through document attributes:
//
//	{abbr-api-first}  spells the abbreviation out, for its first use on a page
//	{abbr-api}        the abbreviation, as <abbr title="..."> linked to the glossary
//	{term-registry}   a defined term, linked to the glossary
//
// Attributes generates the definitions of those attributes. Glossary generates a
// glossary of the terms a set of pages uses. Check reports unknown references and
// abbreviations used before they are spelled out.
package termbase

import (
	"bufio"
	"bytes"
	"fmt"
	"os"
	"regexp"
	"sort"
	"strings"
	"unicode"
	"unicode/utf8"

	"golang.org/x/text/collate"
	"golang.org/x/text/language"
	"gopkg.in/yaml.v3"
)

// Form is a term in one language.
type Form struct {
	Short      string `yaml:"short"`
	Full       string `yaml:"full"`
	Definition string `yaml:"definition"`
}

// Source says where a term was checked.
type Source struct {
	Name    string `yaml:"name"`
	URL     string `yaml:"url"`
	Checked string `yaml:"checked"`
}

// Term is one entry of the term base.
type Term struct {
	ID     string `yaml:"id"`
	Kind   string `yaml:"kind"`
	EN     Form   `yaml:"en"`
	FR     Form   `yaml:"fr"`
	Source Source `yaml:"source"`
}

// Base is the whole term base.
type Base struct {
	Terms []Term `yaml:"terms"`
	byID  map[string]*Term
}

// Finding is a problem found on a page.
type Finding struct {
	File string
	Line int
	Msg  string
}

func (f Finding) String() string { return fmt.Sprintf("%s:%d: %s", f.File, f.Line, f.Msg) }

const (
	Abbreviation = "abbreviation"
	TermKind     = "term"
)

var idPattern = regexp.MustCompile(`^[a-z0-9]+(-[a-z0-9]+)*$`)

// Load reads and validates a term base file.
func Load(path string) (*Base, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	dec := yaml.NewDecoder(bytes.NewReader(data))
	dec.KnownFields(true)
	var b Base
	if err := dec.Decode(&b); err != nil {
		return nil, fmt.Errorf("%s: %w", path, err)
	}
	b.byID = map[string]*Term{}
	for i := range b.Terms {
		t := &b.Terms[i]
		if !idPattern.MatchString(t.ID) {
			return nil, fmt.Errorf("%s: term %q: id must match %s", path, t.ID, idPattern)
		}
		if b.byID[t.ID] != nil {
			return nil, fmt.Errorf("%s: term %q is defined twice", path, t.ID)
		}
		if t.Kind != Abbreviation && t.Kind != TermKind {
			return nil, fmt.Errorf("%s: term %q: kind must be %q or %q, not %q", path, t.ID, Abbreviation, TermKind, t.Kind)
		}
		for lang, f := range map[string]Form{"en": t.EN, "fr": t.FR} {
			if f.Full == "" || f.Definition == "" {
				return nil, fmt.Errorf("%s: term %q: %s needs full and definition", path, t.ID, lang)
			}
			if t.Kind == Abbreviation && f.Short == "" {
				return nil, fmt.Errorf("%s: term %q: %s abbreviation needs short", path, t.ID, lang)
			}
		}
		b.byID[t.ID] = t
	}
	return &b, nil
}

func (t *Term) form(lang string) Form {
	if lang == "fr" {
		return t.FR
	}
	return t.EN
}

func (t *Term) headword(lang string) string {
	f := t.form(lang)
	if t.Kind == Abbreviation {
		return f.Short
	}
	return f.Full
}

var htmlEscaper = strings.NewReplacer("&", "&amp;", `"`, "&quot;", "<", "&lt;", ">", "&gt;")

// macroText escapes text placed between the brackets of an AsciiDoc macro.
func macroText(s string) string { return strings.ReplaceAll(s, "]", `\]`) }

// Attributes returns the attribute definitions for every term, in one language.
// glossaryXref is the path of the glossary page, as an xref target from the pages.
func (b *Base) Attributes(lang, glossaryXref string) string {
	var sb strings.Builder
	sb.WriteString("// Generated by termgen from the FPSOT term base. Do not edit.\n")
	for _, t := range b.sorted() {
		f := t.form(lang)
		target := glossaryXref + "#gl-" + t.ID
		if t.Kind == TermKind {
			fmt.Fprintf(&sb, ":term-%s: xref:%s[%s]\n", t.ID, target, macroText(f.Full))
			continue
		}
		abbr := fmt.Sprintf(`<abbr title="%s">%s</abbr>`, htmlEscaper.Replace(f.Full), htmlEscaper.Replace(f.Short))
		// The <abbr> HTML sits in its own attribute, defined with pass:[] so it is stored
		// raw. A pass:[] inside the xref text would not be expanded at reference time.
		fmt.Fprintf(&sb, "ifdef::backend-html5[]\n:abbr-%s-html: pass:[%s]\n:abbr-%s: xref:%s[{abbr-%s-html}]\nendif::[]\n",
			t.ID, macroText(abbr), t.ID, target, t.ID)
		fmt.Fprintf(&sb, "ifndef::backend-html5[]\n:abbr-%s: xref:%s[%s]\nendif::[]\n", t.ID, target, macroText(f.Short))
		fmt.Fprintf(&sb, ":abbr-%s-first: %s\n", t.ID, firstForm(t.ID, f))
	}
	return sb.String()
}

// firstForm spells an abbreviation out for its first use on a page: "full ({abbr-id})".
// When the full form already holds the abbreviation as a word, such as "document RFC",
// that word becomes the abbreviation itself instead of repeating it in brackets.
func firstForm(id string, f Form) string {
	ref := "{abbr-" + id + "}"
	for i := 0; ; {
		j := strings.Index(f.Full[i:], f.Short)
		if j < 0 {
			break
		}
		start, end := i+j, i+j+len(f.Short)
		if !wordRune(lastRune(f.Full[:start])) && !wordRune(firstRune(f.Full[end:])) {
			return f.Full[:start] + ref + f.Full[end:]
		}
		i = start + 1
	}
	return f.Full + " (" + ref + ")"
}

// wordRune reports whether r is a letter or a digit. The zero rune (no neighbour) is not.
func wordRune(r rune) bool { return unicode.IsLetter(r) || unicode.IsDigit(r) }

func firstRune(s string) rune {
	r, _ := utf8.DecodeRuneInString(s)
	if r == utf8.RuneError {
		return 0
	}
	return r
}

func lastRune(s string) rune {
	r, _ := utf8.DecodeLastRuneInString(s)
	if r == utf8.RuneError {
		return 0
	}
	return r
}

func (b *Base) sorted() []*Term {
	out := make([]*Term, 0, len(b.Terms))
	for i := range b.Terms {
		out = append(out, &b.Terms[i])
	}
	sort.Slice(out, func(i, j int) bool { return out[i].ID < out[j].ID })
	return out
}

var glossaryText = map[string][3]string{
	"en": {"Glossary", "This glossary lists the terms and abbreviations this specification uses.", "This specification uses no defined terms."},
	"fr": {"Glossaire", "Ce glossaire donne les termes et les abréviations de cette spécification.", "Cette spécification n'utilise aucun terme défini."},
}

// Glossary returns a glossary page listing the used terms, sorted in the page language.
func (b *Base) Glossary(lang string, used map[string]bool) string {
	text := glossaryText[lang]
	var terms []*Term
	for _, t := range b.sorted() {
		if used[t.ID] {
			terms = append(terms, t)
		}
	}
	var sb strings.Builder
	fmt.Fprintf(&sb, "= %s\n\n", text[0])
	if len(terms) == 0 {
		fmt.Fprintf(&sb, "%s\n", text[2])
		return sb.String()
	}
	tag := language.CanadianFrench
	if lang != "fr" {
		tag = language.English
	}
	c := collate.New(tag, collate.IgnoreCase)
	sort.SliceStable(terms, func(i, j int) bool {
		return c.CompareString(terms[i].headword(lang), terms[j].headword(lang)) < 0
	})
	fmt.Fprintf(&sb, "%s\n\n[glossary]\n", text[1])
	for _, t := range terms {
		f := t.form(lang)
		if t.Kind == Abbreviation {
			fmt.Fprintf(&sb, "[[gl-%s]]%s (%s):: %s\n", t.ID, f.Short, f.Full, f.Definition)
		} else {
			fmt.Fprintf(&sb, "[[gl-%s]]%s:: %s\n", t.ID, f.Full, f.Definition)
		}
	}
	return sb.String()
}

// ref is one attribute reference found on a page.
type ref struct {
	kind  string // "abbr" or "term"
	id    string
	first bool
	line  int
}

var (
	refPattern = regexp.MustCompile(`\{(abbr|term)-([a-z0-9]+(?:-[a-z0-9]+)*?)(-first)?\}`)
	// Inline passthroughs: `+text+` and +text+. Plain backticks are not listed here,
	// because Asciidoctor substitutes attributes inside them.
	inlineCode = regexp.MustCompile("`\\+[^`]*\\+`|\\+[^+]+\\+")
	// Blocks whose content Asciidoctor does not substitute attributes in.
	verbatim = map[string]bool{"----": true, "....": true, "++++": true, "////": true}
)

// refs returns the attribute references of one file, outside verbatim blocks,
// comments and inline passthroughs.
func refs(path string) ([]ref, error) {
	f, err := os.Open(path)
	if err != nil {
		return nil, err
	}
	defer f.Close()
	var out []ref
	s := bufio.NewScanner(f)
	s.Buffer(make([]byte, 1024*1024), 1024*1024)
	open := ""
	for n := 1; s.Scan(); n++ {
		line := strings.TrimRight(s.Text(), "\r")
		if n == 1 {
			line = strings.TrimPrefix(line, "\ufeff")
		}
		if verbatim[line] {
			if open == "" {
				open = line
			} else if open == line {
				open = ""
			}
			continue
		}
		if open != "" || strings.HasPrefix(line, "//") {
			continue
		}
		line = inlineCode.ReplaceAllString(line, "")
		for _, m := range refPattern.FindAllStringSubmatch(line, -1) {
			out = append(out, ref{kind: m[1], id: m[2], first: m[3] != "", line: n})
		}
	}
	return out, s.Err()
}

// Used returns the IDs referenced by the given files.
func Used(files []string) (map[string]bool, error) {
	used := map[string]bool{}
	for _, file := range files {
		rs, err := refs(file)
		if err != nil {
			return nil, err
		}
		for _, r := range rs {
			used[r.id] = true
		}
	}
	return used, nil
}

// Check reports unknown references, references of the wrong kind, and abbreviations
// used on a page before that page spells them out.
func (b *Base) Check(files []string) []Finding {
	var out []Finding
	for _, file := range files {
		rs, err := refs(file)
		if err != nil {
			out = append(out, Finding{file, 0, err.Error()})
			continue
		}
		spelled := map[string]bool{}
		for _, r := range rs {
			t := b.byID[r.id]
			switch {
			case t == nil:
				out = append(out, Finding{file, r.line, fmt.Sprintf("unknown term %q", r.id)})
			case r.kind == "abbr" && t.Kind != Abbreviation:
				out = append(out, Finding{file, r.line, fmt.Sprintf("%q is a term, use {term-%s}", r.id, r.id)})
			case r.kind == "term" && t.Kind != TermKind:
				out = append(out, Finding{file, r.line, fmt.Sprintf("%q is an abbreviation, use {abbr-%s-first} or {abbr-%s}", r.id, r.id, r.id)})
			case r.kind == "abbr" && r.first:
				spelled[r.id] = true
			case r.kind == "abbr" && !spelled[r.id]:
				out = append(out, Finding{file, r.line, fmt.Sprintf("{abbr-%s} used before {abbr-%s-first} on this page", r.id, r.id)})
			}
		}
	}
	return out
}
